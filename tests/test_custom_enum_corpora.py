"""The local corpora that let the two `custom_enum` fields be scored as concepts.

`sequencing_platform` and `dna_extraction_kit` have no ontology node, so their corpora are
generated by `harmonize/build_custom_enum_corpora.py` from the schema's allowed values and
cMD's curated vocabulary. `host_species` does have one -- the two NCIt concepts its
`static.enum` names -- so `harmonize/build_host_species_corpus.py` takes its alias rows from
NCIt's own synonyms. These guard the property the crosswalks exist for: the schema spelling
and the curated spelling of one thing resolve to one code, while two different things stay
apart.
"""
import pathlib
import sys

import pytest

BENCH = pathlib.Path(__file__).resolve().parents[1] / "benchmarks" / "cmd_sonnet5"
sys.path.insert(0, str(BENCH / "harmonize"))

import crosswalk  # noqa: E402

FIELDS = ("sequencing_platform", "dna_extraction_kit", "host_species")

# (schema spelling, curated spelling) pairs that must share a concept.
ALIGNED = [
    ("sequencing_platform", "Illumina HiSeq", "IlluminaHiSeq"),
    ("sequencing_platform", "Illumina NovaSeq", "IlluminaNovaSeq"),
    ("sequencing_platform", "Ion Torrent Proton", "IonProton"),
    ("dna_extraction_kit", "QIAGEN", "Qiagen"),
    ("dna_extraction_kit", "TIANGEN", "Tiangen"),
    ("dna_extraction_kit", "Norgen Biotek", "NorgenBiotek"),
    ("dna_extraction_kit", "MP Biomedicals", "MPBio"),
    # host_species is ontology backed: "Homo sapiens" is a recorded NCIt synonym of
    # C14225 "Human", so this alignment comes from NCIt and is not authored here.
    ("host_species", "Human", "Homo sapiens"),
    ("host_species", "Mouse", "Mus"),
]

# Pairs that must NOT collapse: the crosswalk aligns spellings, not products.
DISTINCT = [
    ("dna_extraction_kit", "QIAGEN", "QIAamp"),
    ("dna_extraction_kit", "QIAGEN", "PowerSoil DNA Isolation Kit"),
    ("dna_extraction_kit", "MO BIO Laboratories", "Norgen Biotek"),
    ("sequencing_platform", "Illumina HiSeq", "Illumina MiSeq"),
    ("host_species", "Human", "Mouse"),
]


@pytest.mark.parametrize("field", FIELDS)
def test_corpus_is_registered_and_present(field):
    path = crosswalk.corpus_csv(field)
    assert path is not None and path.exists(), f"no corpus for {field}"


@pytest.mark.parametrize("field,schema_form,curated_form", ALIGNED)
def test_schema_and_curated_spellings_share_a_concept(field, schema_form, curated_form):
    cm = crosswalk.corpus_code_map(field)
    a, b = cm.get(crosswalk.norm(schema_form)), cm.get(crosswalk.norm(curated_form))
    assert a and b, f"{schema_form!r}/{curated_form!r} missing from the {field} corpus"
    assert a == b, f"{schema_form!r} -> {a}, {curated_form!r} -> {b}"


@pytest.mark.parametrize("field,one,other", DISTINCT)
def test_different_products_keep_different_concepts(field, one, other):
    cm = crosswalk.corpus_code_map(field)
    a, b = cm.get(crosswalk.norm(one)), cm.get(crosswalk.norm(other))
    assert a and b, f"{one!r}/{other!r} missing from the {field} corpus"
    assert a != b, f"{one!r} and {other!r} both map to {a}"


@pytest.mark.parametrize("field", FIELDS)
def test_every_surface_form_resolves(field):
    import csv
    with crosswalk.corpus_csv(field).open() as fh:
        rows = list(csv.DictReader(fh))
    assert rows
    for r in rows:
        assert r["obo_id"].startswith(("CMDPLAT:", "CMDKIT:", "NCIT:")), r["obo_id"]
        assert r["label"].strip(), r
